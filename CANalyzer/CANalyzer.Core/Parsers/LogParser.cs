using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using CANalyzer.Core.Models;

namespace CANalyzer.Core.Parsers
{
    /// <summary>
    /// Основной класс парсера для обратной совместимости
    /// </summary>
    public class LogParser : ILogParser
    {
        public List<CANMessage> Parse(string filePath)
        {
            if (!File.Exists(filePath))
                throw new FileNotFoundException($"File not found: {filePath}");

            var extension = Path.GetExtension(filePath).ToLower();
            
            return extension switch
            {
                ".csv" => ParseCSV(filePath),
                ".asc" => ParseASC(filePath),
                ".trc" => ParseCSV(filePath), // TRC тоже парсим как CSV
                _ => throw new NotSupportedException($"File format {extension} is not supported")
            };
        }
        
        /// <summary>
        /// Парсер для CSV-файлов PEAK-Converter
        /// Формат: Number,Time (ms),Bus,Direction,Type,ID/PID (hex),Reserved,VCID,SDT,AF,RRS,SEC,Length,Data...
        /// </summary>
        public List<CANMessage> ParseCSV(string filePath)
        {
            var messages = new List<CANMessage>();
            
            using var reader = new StreamReader(filePath, Encoding.UTF8);
            bool dataSectionStarted = false;
            int lineNumber = 0;
            
            while (!reader.EndOfStream)
            {
                var line = reader.ReadLine()?.Trim();
                lineNumber++;
                
                if (string.IsNullOrEmpty(line))
                    continue;
                
                // Пропускаем метаданные и комментарии
                if (line.StartsWith("$") || line.StartsWith("//") || line.StartsWith("#") ||
                    line.Contains("Glossary:") || line.Contains("Generated by") || 
                    line.Contains("Start time:") || line.Contains("----------------------------------------------------------------"))
                    continue;
                
                // Находим начало данных (заголовок таблицы)
                if (line.Contains("Number,Time (ms),Bus,Direction,Type,ID/PID (hex),Reserved,VCID,SDT,AF,RRS,SEC,Length"))
                {
                    dataSectionStarted = true;
                    continue;
                }
                
                // Если еще не дошли до данных, пропускаем
                if (!dataSectionStarted)
                    continue;
                
                try
                {
                    // Разделяем строку на части
                    var parts = line.Split(',');
                    
                    // Минимальная проверка: должен быть номер, время, шина и ID
                    if (parts.Length < 6)
                        continue;
                    
                    // Парсим основные поля из вашего CSV формата:
                    // 1,0.060,1,Rx,FB,0102,-,-,-,-,-,-,8,A2,0A,00,00,00,00,00,29
                    
                    // Время (мс) -> преобразуем в микросекунды для совместимости
                    var timeMs = double.Parse(parts[1], CultureInfo.InvariantCulture);
                    var timestamp = (ulong)(timeMs * 1000); // мс -> мкс
                    
                    // ID (hex) - убираем возможные префиксы
                    var idStr = parts[5].Trim();
                    if (idStr == "-" || string.IsNullOrEmpty(idStr))
                        continue;
                        
                    var id = Convert.ToUInt32(idStr, 16);
                    
                    // Длина данных (может быть в 13-й колонке)
                    var length = 0;
                    if (parts.Length > 12 && int.TryParse(parts[12], out var len))
                        length = len;
                    
                    // Данные (начинаются с 13-й колонки или с 14-й, если есть D0,D1...)
                    var dataBytes = new List<byte>();
                    var dataStartIndex = 13;
                    
                    // Находим начало данных (может быть обозначено как D0 или просто hex)
                    for (int i = dataStartIndex; i < parts.Length; i++)
                    {
                        if (i >= parts.Length)
                            break;
                            
                        var dataStr = parts[i].Trim();
                        
                        // Пропускаем пустые и разделители
                        if (string.IsNullOrEmpty(dataStr) || dataStr == "-" || 
                            dataStr.StartsWith("D") || dataStr.Contains("..."))
                            continue;
                        
                        // Пытаемся распарсить как hex байт
                        if (byte.TryParse(dataStr, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out byte dataByte))
                        {
                            dataBytes.Add(dataByte);
                            
                            // Ограничиваем по длине, если она указана
                            if (length > 0 && dataBytes.Count >= length)
                                break;
                        }
                    }
                    
                    // Если не нашли данные в ожидаемом месте, пробуем альтернативный парсинг
                    if (dataBytes.Count == 0)
                    {
                        // Пробуем найти данные после ID
                        for (int i = 6; i < parts.Length; i++)
                        {
                            if (i >= parts.Length)
                                break;
                                
                            var dataStr = parts[i].Trim();
                            if (string.IsNullOrEmpty(dataStr) || dataStr == "-")
                                continue;
                                
                            // Пробуем распарсить любые hex значения
                            if (dataStr.Length == 2 && 
                                byte.TryParse(dataStr, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out byte b))
                            {
                                dataBytes.Add(b);
                            }
                        }
                    }
                    
                    // Создаем сообщение
                    var message = new CANMessage(
                        id: id,
                        data: dataBytes.ToArray(),
                        timestamp: timestamp
                    );
                    
                    // Добавляем дополнительную информацию (если нужно расширить модель)
                    // message.Bus = int.Parse(parts[2]);
                    // message.Direction = parts[3];
                    // message.Type = parts[4];
                    
                    messages.Add(message);
                }
                catch (Exception ex)
                {
                    // Логируем ошибку для отладки
                    Console.WriteLine($"Error parsing line {lineNumber}: {ex.Message}");
                    // Продолжаем обработку остальных строк
                }
            }
            
            return messages;
        }
        
        /// <summary>
        /// Парсер для ASC файлов (оставляем как было)
        /// </summary>
        public List<CANMessage> ParseASC(string filePath)
        {
            var messages = new List<CANMessage>();
            
            using var reader = new StreamReader(filePath, Encoding.UTF8);
            while (!reader.EndOfStream)
            {
                var line = reader.ReadLine()?.Trim();
                if (string.IsNullOrEmpty(line)) continue;
                
                // Упрощенный парсер для ASC формата
                if (line.StartsWith("0") || line.Contains("Rx"))
                {
                    try
                    {
                        var parts = line.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
                        if (parts.Length < 4) continue;
                        
                        var timestamp = Convert.ToUInt64(double.Parse(parts[0]) * 1000000); // мкс
                        var id = Convert.ToUInt32(parts[2], 16);
                        var data = new List<byte>();
                        
                        for (int i = 3; i < parts.Length; i++)
                        {
                            if (parts[i].Length == 2 && byte.TryParse(parts[i], 
                                System.Globalization.NumberStyles.HexNumber, null, out byte b))
                            {
                                data.Add(b);
                            }
                        }
                        
                        messages.Add(new CANMessage(id, data.ToArray(), timestamp));
                    }
                    catch
                    {
                        // Пропускаем некорректные строки
                    }
                }
            }
            
            return messages;
        }
    }
}