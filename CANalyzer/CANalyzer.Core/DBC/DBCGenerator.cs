using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using CANalyzer.Core.Models;

namespace CANalyzer.Core.DBC
{
    public interface IDBCGenerator
    {
        void AddMessage(uint messageId, string messageName, List<CANSignal> signals, int dlc = 8, string transmitter = "DBG");
        void AddDetectedSignals(Dictionary<uint, List<CANSignal>> detectedSignals);
        string Generate();
        void SaveToFile(string filePath);
        void Clear();
    }

    public class DBCGenerator : IDBCGenerator
    {
        private readonly Dictionary<uint, DBCMessageInfo> _messages = new();
        private readonly Dictionary<string, string> _valueTables = new();
        private int _nextMessageNumber = 1000;

        public class DBCMessageInfo
        {
            public uint Id { get; set; }
            public string Name { get; set; }
            public int DLC { get; set; }
            public string Transmitter { get; set; }
            public List<CANSignal> Signals { get; set; } = new();
            public string Comment { get; set; } = string.Empty;
        }

        public void AddMessage(uint messageId, string messageName, List<CANSignal> signals, int dlc = 8, string transmitter = "DBG")
        {
            if (signals == null || signals.Count == 0)
                return;

            // Автоматически определяем DLC если не указан
            if (dlc <= 0)
            {
                var maxBit = signals.Max(s => s.StartBit + s.Length);
                dlc = (maxBit + 7) / 8;
                dlc = Math.Clamp(dlc, 1, 64); // CAN FD поддерживает до 64 байт
            }

            _messages[messageId] = new DBCMessageInfo
            {
                Id = messageId,
                Name = string.IsNullOrEmpty(messageName) ? $"MSG_{messageId:X}" : messageName,
                DLC = dlc,
                Transmitter = transmitter,
                Signals = signals
            };

            // Автоматически создаем таблицы значений для enum-сигналов
            CreateValueTables(signals, messageId);
        }

        public void AddDetectedSignals(Dictionary<uint, List<CANSignal>> detectedSignals)
        {
            foreach (var kvp in detectedSignals)
            {
                if (kvp.Value.Count > 0)
                {
                    var messageName = $"Detected_0x{kvp.Key:X}";
                    AddMessage(kvp.Key, messageName, kvp.Value);
                }
            }
        }

        private void CreateValueTables(List<CANSignal> signals, uint messageId)
        {
            foreach (var signal in signals.Where(s => s.Type == SignalType.State || s.Type == SignalType.Counter))
            {
                if (signal.Length <= 4) // Для коротких сигналов создаем enum таблицу
                {
                    var maxValue = (int)Math.Pow(2, signal.Length);
                    var tableName = $"TAB_{signal.Name}";
                    
                    var sb = new StringBuilder();
                    for (int i = 0; i < maxValue; i++)
                    {
                        sb.Append($"{i} \"State_{i}\" ");
                    }
                    
                    _valueTables[$"{messageId}_{signal.Name}"] = sb.ToString();
                }
            }
        }

        public string Generate()
        {
            var sb = new StringBuilder();
            
            // Заголовок DBC
            sb.AppendLine("VERSION \"Generated by CANalyzer Professional\"");
            sb.AppendLine();
            
            // Раздел новых символов
            sb.AppendLine("NS_ :");
            AppendIndented(sb, "NS_DESC_");
            AppendIndented(sb, "CM_");
            AppendIndented(sb, "BA_DEF_");
            AppendIndented(sb, "BA_");
            AppendIndented(sb, "VAL_");
            AppendIndented(sb, "CAT_DEF_");
            AppendIndented(sb, "CAT_");
            AppendIndented(sb, "FILTER");
            AppendIndented(sb, "BA_DEF_DEF_");
            AppendIndented(sb, "EV_DATA_");
            AppendIndented(sb, "ENVVAR_DATA_");
            AppendIndented(sb, "SGTYPE_");
            AppendIndented(sb, "SGTYPE_VAL_");
            AppendIndented(sb, "BA_DEF_SGTYPE_");
            AppendIndented(sb, "BA_SGTYPE_");
            AppendIndented(sb, "SIG_TYPE_REF_");
            AppendIndented(sb, "VAL_TABLE_");
            AppendIndented(sb, "SIG_GROUP_");
            AppendIndented(sb, "SIG_VALTYPE_");
            AppendIndented(sb, "SIGTYPE_VALTYPE_");
            AppendIndented(sb, "BO_TX_BU_");
            AppendIndented(sb, "BA_DEF_REL_");
            AppendIndented(sb, "BA_REL_");
            AppendIndented(sb, "BA_DEF_DEF_REL_");
            AppendIndented(sb, "BU_SG_REL_");
            AppendIndented(sb, "BU_EV_REL_");
            AppendIndented(sb, "BU_BO_REL_");
            sb.AppendLine();
            
            // Раздел шины
            sb.AppendLine("BS_:");
            sb.AppendLine();
            
            // Раздел узлов
            sb.Append("BU_:");
            var uniqueTransmitters = _messages.Values.Select(m => m.Transmitter).Distinct();
            foreach (var transmitter in uniqueTransmitters)
            {
                sb.Append($" {transmitter}");
            }
            sb.AppendLine();
            sb.AppendLine();
            
            // Сообщения
            foreach (var msgInfo in _messages.Values.OrderBy(m => m.Id))
            {
                // BO_ ID Name: DLC Transmitter
                sb.AppendLine($"BO_ {msgInfo.Id} {msgInfo.Name}: {msgInfo.DLC} {msgInfo.Transmitter}");
                
                // Сигналы
                foreach (var signal in msgInfo.Signals)
                {
                    var byteOrder = signal.ByteOrder == SignalByteOrder.Intel ? "1" : "0";
                    var sign = signal.Factor >= 0 ? "+" : "-";
                    
                    // Определяем множитель и смещение
                    double factor = Math.Abs(signal.Factor) > 0.0001 ? signal.Factor : 1.0;
                    double offset = signal.Offset;
                    
                    // Определяем min/max на основе типа
                    double min = signal.MinPhysical;
                    double max = signal.MaxPhysical;
                    
                    if (signal.Type == SignalType.Boolean)
                    {
                        min = 0;
                        max = 1;
                    }
                    else if (Math.Abs(max - min) < 0.001)
                    {
                        max = min + Math.Pow(2, signal.Length) - 1;
                    }
                    
                    // SG_ SignalName : StartBit|Length@ByteOrderSign (Factor,Offset) [Min|Max] "Unit" Receiver
                    sb.AppendLine($" SG_ {signal.Name} : {signal.StartBit}|{signal.Length}@{byteOrder}{sign} ({factor:0.#####},{offset:0.#####}) [{min:0.#####}|{max:0.#####}] \"{signal.Unit}\" {msgInfo.Transmitter}");
                }
                
                sb.AppendLine();
            }
            
            // Таблицы значений
            foreach (var kvp in _valueTables)
            {
                var parts = kvp.Key.Split('_');
                if (parts.Length >= 2 && uint.TryParse(parts[0], out uint msgId))
                {
                    var signalName = parts[1];
                    sb.AppendLine($"VAL_ {msgId} {signalName} {kvp.Value};");
                }
            }
            sb.AppendLine();
            
            // Комментарии
            foreach (var msgInfo in _messages.Values)
            {
                if (!string.IsNullOrEmpty(msgInfo.Comment))
                {
                    sb.AppendLine($"CM_ BO_ {msgInfo.Id} \"{msgInfo.Comment}\";");
                }
                
                foreach (var signal in msgInfo.Signals)
                {
                    if (!string.IsNullOrEmpty(signal.Description))
                    {
                        sb.AppendLine($"CM_ SG_ {msgInfo.Id} {signal.Name} \"{signal.Description}\";");
                    }
                }
            }
            
            return sb.ToString();
        }

        private void AppendIndented(StringBuilder sb, string line)
        {
            sb.AppendLine($"\t{line}");
        }

        public void SaveToFile(string filePath)
        {
            var directory = Path.GetDirectoryName(filePath);
            if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
            {
                Directory.CreateDirectory(directory);
            }
            
            var dbcContent = Generate();
            File.WriteAllText(filePath, dbcContent, Encoding.UTF8);
        }

        public void Clear()
        {
            _messages.Clear();
            _valueTables.Clear();
            _nextMessageNumber = 1000;
        }

        private uint GetNextMessageId()
        {
            return (uint)(_nextMessageNumber++);
        }
    }
}